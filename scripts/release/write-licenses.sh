#!/bin/sh
# Writes the license files of a release into OUTDIR (created if missing):
#   LICENSE                   this repository's license (copied)
#   SQLITE-PUBLIC-DOMAIN.txt  SQLite's public-domain statement, the pinned
#                             version, source URL and checksums
#   NOTICE.md                 what is statically linked, per platform
#
# Usage: scripts/release/write-licenses.sh OUTDIR RELEASE
# The SQLite facts come from third_party/sqlite/. The per-platform runtime
# facts are the claims the build is expected to satisfy; the linkage reports
# shipped with the release (licenses/linkage/) show what each binary really
# loads.
set -eu

script_dir=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$script_dir/../.." && pwd)
pin_dir=$root/third_party/sqlite

die() {
	printf 'write-licenses: %s\n' "$*" >&2
	exit 1
}

[ $# -eq 2 ] || die "usage: $0 OUTDIR RELEASE"
out=$1
release=$2
case $release in
v[0-9]*) ;;
*) die "release must look like v1.2.3: $release" ;;
esac

version=
archive=
url=
while IFS='=' read -r key value; do
	case $key in
	version) version=$value ;;
	archive) archive=$value ;;
	url) url=$value ;;
	'' | '#'*) ;;
	*) die "unknown key in VERSION: $key" ;;
	esac
done <"$pin_dir/VERSION"
[ -n "$version" ] && [ -n "$archive" ] && [ -n "$url" ] || die "incomplete VERSION"

sha256=$(awk -v n="$archive" '$2 == n { print $1 }' "$pin_dir/SHA256")
sha3=$(awk -v n="$archive" '$2 == n { print $1 }' "$pin_dir/SHA3-256")
[ "${#sha256}" -eq 64 ] && [ "${#sha3}" -eq 64 ] || die "pins for $archive are missing"

mkdir -p "$out"
cp "$root/LICENSE" "$out/LICENSE"

cat >"$out/SQLITE-PUBLIC-DOMAIN.txt" <<EOF
SQLite is in the public domain.

Component:  SQLite amalgamation (sqlite3.c, sqlite3.h)
Version:    $version
Source:     $url
Archive:    $archive
SHA256:     $sha256
SHA3-256:   $sha3
            (SHA3-256 as listed on https://www.sqlite.org/download.html)

The dedication, as published at https://www.sqlite.org/copyright.html:

  All of the code and documentation in SQLite has been dedicated to the
  public domain by the authors. All code authors, and representatives of
  the companies they work for, have signed affidavits dedicating their
  contributions to the public domain and originals of those signed
  affidavits are stored in a firesafe at the main offices of Hwaci. All
  contributors are citizens of countries that allow creative works to be
  dedicated into the public domain.

  Anyone is free to copy, modify, publish, use, compile, sell, or
  distribute the original SQLite code, either in source code form or as a
  compiled binary, for any purpose, commercial or non-commercial, and by
  any means.

The same release of sqlite3.c states, in its header comment:

  The author disclaims copyright to this source code.  In place of
  a legal notice, here is a blessing:

     May you do good and not evil.
     May you find forgiveness for yourself and forgive others.
     May you share freely, never taking more than you give.
EOF

cat >"$out/NOTICE.md" <<EOF
# Notices for hqq-sqlite-server $release

This file is generated by scripts/release/write-licenses.sh. It lists the
third-party code that is compiled into the release binaries
hqq-sqlite-server_<os>_<arch>[.exe] and how each platform binary gets its C
runtime. It is a factual description, not legal advice.

## Statically linked into the server

| Component | Version | License | Text |
|---|---|---|---|
| libhqq (this repository: c/, examples/sqlite/server/) | $release | MIT | LICENSE |
| SQLite amalgamation (sqlite3.c, sqlite3.h) | $version | Public domain | SQLITE-PUBLIC-DOMAIN.txt |

The SQLite amalgamation is pinned in third_party/sqlite/ (\`$archive\`,
SHA256 \`$sha256\`). It is downloaded and checked by
scripts/release/fetch-sqlite.sh (or fetch-sqlite.ps1) and built from source
in the release workflow; no SQLite binary is distributed.

## C runtime, per platform

The server is C. The table gives what each binary is expected to load at run
time. The file licenses/linkage/<binary>.txt in this release lists the
dependencies the built binary actually has.

| Binary | C library | Linked into the binary | Loaded from the host system |
|---|---|---|---|
| hqq-sqlite-server_linux_amd64 | glibc (libc.so.6, dynamic loader) | libgcc (static, -static-libgcc) | glibc |
| hqq-sqlite-server_linux_arm64 | glibc (libc.so.6, dynamic loader) | libgcc (static, -static-libgcc) | glibc |
| hqq-sqlite-server_darwin_arm64 | libSystem.B.dylib | nothing else | libSystem (part of macOS) |
| hqq-sqlite-server_darwin_amd64 | libSystem.B.dylib | nothing else | libSystem (part of macOS) |
| hqq-sqlite-server_windows_amd64.exe | none (static CRT, /MT) | MSVC static CRT, UCRT | Windows system DLLs only |
| hqq-sqlite-server_windows_arm64.exe | none (static CRT, /MT) | MSVC static CRT, UCRT | Windows system DLLs only |

Why no redistribution obligation arises from the C runtime: the system
libraries (glibc, libSystem, Windows DLLs) are not copied into the release;
the binary only refers to them by name and they come from the host. Code
linked into the binary is limited to libhqq, SQLite and, on Linux, the
libgcc support routines (GCC Runtime Library Exception). The Windows
binaries carry the static CRT, so they do not need the redistributable
runtime. The Windows rows apply only to releases that include Windows
binaries.

## Where the notices are

The release ships licenses.tar.gz, which contains this licenses/ tree:
LICENSE, SQLITE-PUBLIC-DOMAIN.txt, NOTICE.md and linkage/*.txt. The same
files are in the workflow run's artifacts.
EOF
