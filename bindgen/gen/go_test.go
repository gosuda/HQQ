func goldenPath(c goCase) string {
	return filepath.Join("testdata", "go", c.name, c.name+"_client.go")
}

// TestGoGolden compares the generated clients with the committed ones. The committed files are also the
// packages that TestGoGoldenBuilds compiles and vets with the go tool. Run with -update-go to rewrite them.
func TestGoGolden(t *testing.T) {
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			spec, strip := c.load(t)
			got := generateGo(t, spec, strip, c.source)
			path := goldenPath(c)
			if *updateGoGolden {
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, got, 0o644); err != nil {
					t.Fatal(err)
				}
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v (run the test with -update-go to create it)", err)
			}
			if !bytes.Equal(got, want) {
				t.Errorf("generated %s differs from %s (run with -update-go after checking the diff)\n%s",
					c.name, path, firstDifference(want, got))
			}
		})
	}
}

// firstDifference names the first line at which two outputs differ.
func firstDifference(want, got []byte) string {
	w, g := strings.Split(string(want), "\n"), strings.Split(string(got), "\n")
	for i := 0; i < len(w) || i < len(g); i++ {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			return fmt.Sprintf("line %d:\n  committed: %q\n  generated: %q", i+1, wl, gl)
		}
	}
	return "no differing line"
}

// TestGoHeaderAndDigest pins the first line (9.2) and the digest of the worked examples against the
// SHA-256 that the design document prints.
func TestGoHeaderAndDigest(t *testing.T) {
	for _, c := range []struct{ rel, strip, digest string }{
		{"microlib/microlib.idl", "ml_", "06a738744a1ea9f11fb08cc41afbe48e1891c76e60830a276e98cf8c15944e5c"},
		{"sqlite_lowlevel.idl", "", "06a17c1abf350b8ba75b1249f05524b638f41c83f9c296326d638ba35c8b5850"},
	} {
		spec := loadSpec(t, c.rel, c.strip)
		out := generateGo(t, spec, c.strip, "../../testdata/"+c.rel)
		first, _, _ := strings.Cut(string(out), "\n")
		base := filepath.Base(c.rel)
		want := fmt.Sprintf("// Code generated by hqq-bindgen from %s (interface digest %s). DO NOT EDIT.", base, c.digest)
		if first != want {
			t.Errorf("%s: header\n got %s\nwant %s", c.rel, first, want)
		}
		sum := sha256.Sum256(spec.Canonical())
		if hex.EncodeToString(sum[:]) != c.digest {
			t.Errorf("%s: the canonical text no longer hashes to the documented digest", c.rel)
		}
	}
}

// TestGoDeterministicAndFormatted: the output does not depend on the run and is what gofmt would write.
func TestGoDeterministicAndFormatted(t *testing.T) {
	for _, c := range goldenCases() {
		t.Run(c.name, func(t *testing.T) {
			spec, strip := c.load(t)
			a := generateGo(t, spec, strip, c.source)
			spec2, _ := c.load(t)
			b := generateGo(t, spec2, strip, c.source)
			if !bytes.Equal(a, b) {
				t.Error("two runs give different bytes")
			}
			again, err := format.Source(a)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(a, again) {
				t.Errorf("output is not gofmt-stable:\n%s", firstDifference(a, again))
			}
			for _, bad := range []string{"\r", "/Users/", "/home/", "/tmp/"} {
				if bytes.Contains(a, []byte(bad)) {
					t.Errorf("output contains %q", bad)
				}
			}
		})
	}
}

func TestGoSourceNameIsBaseName(t *testing.T) {
	spec := loadSpec(t, "microlib/microlib.idl", "ml_")
	for in, want := range map[string]string{
		"microlib.idl":                "microlib.idl",
		"../../testdata/microlib.idl": "microlib.idl",
		"/abs/host/path/x.idl":        "x.idl",
		`C:\work\idl\win.idl`:         "win.idl",
		"":                            "microlib.idl",
		"dir/":                        "microlib.idl",
	} {
		out := generateGo(t, spec, "ml_", in)
		first, _, _ := strings.Cut(string(out), "\n")
		if !strings.Contains(first, " from "+want+" (interface digest ") {
			t.Errorf("source %q: header %q does not name %q", in, first, want)
		}
	}
}

func TestGoRejectsBadOptions(t *testing.T) {
	spec := loadSpec(t, "microlib/microlib.idl", "ml_")
	for name, o := range map[string]GoOptions{
		"keyword package":    {Package: "type", Strip: "ml_"},
		"blank package":      {Package: "_", Strip: "ml_"},
		"digit package":      {Package: "1x", Strip: "ml_"},
		"dotted package":     {Package: "a.b", Strip: "ml_"},
		"newline in source":  {Source: "x.idl\npackage evil", Strip: "ml_"},
		"carriage in source": {Source: "x.idl\rfoo", Strip: "ml_"},
		"line separator":     {Source: "x\u2028.idl", Strip: "ml_"},
		"invalid utf-8":      {Source: "x\xff.idl", Strip: "ml_"},
	} {
		if _, err := Go(spec, o); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
	if _, err := Go(nil, GoOptions{}); err == nil {
		t.Error("nil spec: no error")
	}
}

// TestGoPackageOption: the package clause follows GoOptions.Package and defaults to the service.
func TestGoPackageOption(t *testing.T) {
	spec := loadSpec(t, "microlib/microlib.idl", "ml_")
	for pkg, want := range map[string]string{"": "microlib", "ml": "ml", "Client2": "Client2"} {
		files, err := Go(spec, GoOptions{Package: pkg, Strip: "ml_"})
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Contains(files[0].Data, []byte("\npackage "+want+"\n")) {
			t.Errorf("Package %q: no package clause %q", pkg, want)
		}
		if files[0].Name != "microlib_client.go" {
			t.Errorf("file name %q", files[0].Name)
		}
	}
}

// TestGoNameChecksUseEmitterStrip: the emitter re-applies V37 to the names derived from GoOptions.Strip, so
// a strip that differs from the parser's cannot produce a file that does not compile.
func TestGoNameChecksUseEmitterStrip(t *testing.T) {
	cases := []struct {
		name, idl, strip, want string
	}{
		{"reserved Kill", "fn x_kill();", "x_", `"Kill"`},
		{"reserved Close", "fn x_close();", "x_", `"Close"`},
		{"reserved Dial", "fn x_dial();", "x_", `"Dial"`},
		{"reserved Client", "fn x_client();", "x_", `"Client"`},
		{"reserved Conn", "fn x_conn();", "x_", `"Conn"`},
		{"duplicate", "fn p_open(); fn open();", "p_", `"Open"`},
		{"empty name", "fn ml_();", "ml_", "not an exported identifier"},
		{"const collides with method type", "const Open: u8 = 1; fn p_open();", "p_", `"Open"`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			spec := parseIDL(t, "x.idl", "idl 1;\nservice svc;\n"+c.idl+"\n", "")
			_, err := Go(spec, GoOptions{Strip: c.strip})
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("error %v, want one mentioning %s", err, c.want)
			}
		})
	}
}

// TestGoFutureTypeCollisionIsRejected: a function whose name collides with the future type of another is
// a V37 violation, so the emitter never sees it.
func TestGoFutureTypeCollisionIsRejected(t *testing.T) {
	_, err := idl.Parse("x.idl", []byte("idl 1;\nservice svc;\nfn open();\nfn open_future();\n"), idl.Options{})
	if err == nil || !strings.Contains(err.Error(), "V37") {
		t.Errorf("parse error %v, want V37", err)
	}
}
