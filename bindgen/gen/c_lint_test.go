func indentOf(l string) int {
	return len(l) - len(strings.TrimLeft(l, " "))
}

// lockDiscipline checks rule 4 of 9.6 on generated source: after hqqrpc_exec_begin every return, up to the
// hqqrpc_exec_end of the function body, is preceded in its own block by hqqrpc_exec_end. It also checks that the
// lock is taken and released once per function.
func lockDiscipline(src string) []string {
	var problems []string
	var fn string
	var lines []string
	flush := func() {
		if fn == "" {
			return
		}
		begin, end := 0, 0
		locked := false
		for i, l := range lines {
			t := strings.TrimSpace(l)
			switch {
			case t == "hqqrpc_exec_begin(s);" && indentOf(l) == 4:
				begin++
				locked = true
			case t == "hqqrpc_exec_end(s);" && indentOf(l) == 4:
				end++
				locked = false
			case locked && strings.HasPrefix(t, "return "):
				k := indentOf(l)
				found := false
				for j := i - 1; j >= 0 && indentOf(lines[j]) >= k; j-- {
					if strings.TrimSpace(lines[j]) == "hqqrpc_exec_end(s);" && indentOf(lines[j]) == k {
						found = true
						break
					}
				}
				if !found {
					problems = append(problems, fn+": "+t+" returns with the execution lock held")
				}
			}
		}
		if begin != end || begin > 1 {
			problems = append(problems, fn+": exec_begin x"+itoa(begin)+", exec_end x"+itoa(end))
		}
		fn = ""
	}
	for _, l := range strings.Split(src, "\n") {
		if m := regexp.MustCompile(`^static hqqrpc_status (op_\w+)\(`).FindStringSubmatch(l); m != nil {
			flush()
			fn, lines = m[1], nil
			continue
		}
		if fn != "" {
			lines = append(lines, l)
			if l == "}" {
				flush()
			}
		}
	}
	flush()
	return problems
}

// styleProblems checks the layout rules of 9.2 on one generated file.
func styleProblems(name, src string) []string {
	var p []string
	if !strings.HasSuffix(src, "\n") || strings.HasSuffix(src, "\n\n") {
		p = append(p, name+": must end with exactly one newline")
	}
	if strings.Contains(src, "\t") {
		p = append(p, name+": contains a tab")
	}
	if strings.Contains(src, "\r") {
		p = append(p, name+": contains a carriage return")
	}
	for i, l := range strings.Split(src, "\n") {
		if strings.TrimRight(l, " ") != l {
			p = append(p, name+":"+itoa(i+1)+": trailing space")
		}
		if indentOf(l)%4 != 0 && !strings.HasPrefix(strings.TrimSpace(l), "*") {
			p = append(p, name+":"+itoa(i+1)+": indentation is not a multiple of 4")
		}
	}
	if !strings.HasPrefix(src, "/* Code generated by hqq-bindgen from ") || !strings.Contains(strings.SplitN(src, "\n", 2)[0], "(interface digest ") ||
		!strings.HasSuffix(strings.SplitN(src, "\n", 2)[0], "DO NOT EDIT. */") {
		p = append(p, name+": wrong header comment")
	}
	return p
}

// TestCStyleAndLockDiscipline runs the layout and lock checks over the committed outputs and variants.
func TestCStyleAndLockDiscipline(t *testing.T) {
	var all []map[string][]byte
	for _, tc := range cGoldenCases {
		all = append(all, genC(t, parseSpec(t, tc.idl), tc.source))
	}
	all = append(all, genC(t, parseSpec(t, "bindgen/gen/testdata/c/shapes.idl"), "shapes.idl"))
	src, _ := readFile(t, "bindgen/testdata/microlib/microlib.idl")
	all = append(all, genC(t, parseText(t, strings.Replace(src, "@serialize(session)", "@serialize(none)", 1)), "microlib.idl"))

	for _, files := range all {
		for name, data := range files {
			for _, p := range styleProblems(name, string(data)) {
				t.Error(p)
			}
			if strings.HasSuffix(name, ".c") {
				for _, p := range lockDiscipline(string(data)) {
					if !strings.Contains(string(data), "hqqrpc_exec_begin") && !strings.Contains(p, "exec_begin x0") {
						continue
					}
					t.Errorf("%s: %s", name, p)
				}
			}
		}
	}
}

// TestCLockDisciplineCatchesAViolation makes sure that the check itself can fail.
func TestCLockDisciplineCatchesAViolation(t *testing.T) {
	bad := "static hqqrpc_status op_x(hqqrpc_call *c) {\n    hqqrpc_exec_begin(s);\n    if (x)\n        return 1;\n    hqqrpc_exec_end(s);\n    return 0;\n}\n"
	if len(lockDiscipline(bad)) == 0 {
		t.Error("a return with the lock held was not found")
	}
	good := "static hqqrpc_status op_x(hqqrpc_call *c) {\n    hqqrpc_exec_begin(s);\n    if (x) {\n        hqqrpc_exec_end(s);\n        return 1;\n    }\n    hqqrpc_exec_end(s);\n    return 0;\n}\n"
	if p := lockDiscipline(good); len(p) != 0 {
		t.Errorf("good code flagged: %v", p)
	}
}

