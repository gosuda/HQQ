// TestCIdentifiersNeverCollide generates glue for an IDL whose parameters are named like the glue's locals, like the
// C names it uses and like a type of the library: the glue must compile and keep the IDL names.
func TestCIdentifiersNeverCollide(t *testing.T) {
	spec := parseText(t, collideIDL)
	dir := t.TempDir()
	files := genC(t, spec, "collide.idl")
	writeFiles(t, dir, files)
	writeFiles(t, dir, map[string][]byte{"collide.h": []byte(collideHeader)})
	compileObjects(t, dir, nil, filepath.Join(dir, "collide_server.c"))
	if !strings.Contains(string(files["collide_server.c"]), "ret_") {
		t.Error("the IDL name ret_ is not used")
	}
}

// TestCRejectsWhatItCannotExpress covers the errors of Emit for valid IDL.
func TestCRejectsWhatItCannotExpress(t *testing.T) {
	hdr := "idl 1;\nservice bad;\n"
	for _, tc := range []struct{ name, idl, want string }{
		{"shim returning a fixed struct without @c", hdr + "struct P { a: i32; }\nshim fn f() -> P @max_out(16);\n", "needs @c"},
		{"shim out struct without @c", hdr + "struct P { a: i32; }\nshim fn f(out p: P);\n", "needs @c"},
		{"borrowed array of structs without @c", hdr + "struct P { a: i32; }\nfn f(out a: P[]<=2 @borrowed, out n: u32 @len_of(a));\n", "needs @c"},
		{"function named like a generated name", hdr + "fn x();\nfn op_x();\n", "collides"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			spec, err := idl.Parse("bad.idl", []byte(tc.idl), idl.Options{})
			if err != nil {
				t.Fatalf("the test IDL is not valid: %v", err)
			}
			_, err = C(spec, COptions{Source: "bad.idl"})
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error %v, want one containing %q", err, tc.want)
			}
		})
	}
}

// TestCHandleMacrosAreUnique: handle types that differ only in case still get distinct macros.
func TestCHandleMacrosAreUnique(t *testing.T) {
	spec := parseText(t, "idl 1;\nservice mac;\n@c(\"a *\") handle Db destroy xa;\n@c(\"b *\") handle DB destroy xb;\nfn xa(h: Db);\nfn xb(h: DB);\n")
	h := string(genC(t, spec, "mac.idl")["mac_server.h"])
	for _, want := range []string{"#define MAC_H_DB_1 1u", "#define MAC_H_DB_2 2u"} {
		if !strings.Contains(h, want) {
			t.Errorf("header lacks %q:\n%s", want, h)
		}
	}
}

// TestCHeaderSource: the Source option is reduced to a base name and cannot end the comment.
func TestCHeaderSource(t *testing.T) {
	spec := parseSpecText(t)
	for _, tc := range []struct{ source, want string }{
		{"", "from t.idl ("},
		{"a/b/c.idl", "from c.idl ("},
		{`C:\x\y.idl`, "from y.idl ("},
		{"x*/y.idl", "from y.idl ("},
	} {
		files, err := C(spec, COptions{Source: tc.source})
		if err != nil {
			t.Fatal(err)
		}
		first := strings.SplitN(string(files[0].Data), "\n", 2)[0]
		if !strings.Contains(first, tc.want) {
			t.Errorf("Source %q: header %q, want it to contain %q", tc.source, first, tc.want)
		}
	}
}

func parseSpecText(t *testing.T) *idl.Spec {
	return parseText(t, "idl 1;\nservice t;\nfn f();\n")
}
