package extract

import (
	"encoding/hex"
	"fmt"
	"strings"
)

// CHeader renders c/tests/generated/rpc_vectors.h from the vector file. The layout follows
// c/tools/gen_constants.py: guards, static const tables, 16 bytes per line, no timestamps.
func (f *File) CHeader() []byte {
	var o strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&o, format+"\n", args...) }

	w("/* Generated by bindgen/internal/vectors from spec/toolchain/BINDGEN.md (10.1). Do not edit. */")
	w("#ifndef HQQ_TESTS_RPC_VECTORS_H")
	w("#define HQQ_TESTS_RPC_VECTORS_H")
	w("")
	w("#include <stddef.h>")
	w("#include <stdint.h>")
	w("")
	w("#ifdef __cplusplus")
	w("extern \"C\" {")
	w("#endif")
	w("")
	w("/* Direction of a frame: the client sends C2S frames, the server sends S2C frames. */")
	w("#define HQQ_RPCVEC_C2S 0")
	w("#define HQQ_RPCVEC_S2C 1")
	w("")
	w("typedef struct hqq_rpcvec_frame {")
	w("    const char *name;")
	w("    uint32_t id;               /* the id field of the frame header */")
	w("    int dir;                   /* HQQ_RPCVEC_C2S or HQQ_RPCVEC_S2C */")
	w("    const unsigned char *data; /* the whole frame: header and body */")
	w("    size_t len;")
	w("} hqq_rpcvec_frame;")
	w("")
	w("/* Link geometry of the frame groups (BINDGEN.md 4.14). */")
	w("#define HQQ_RPCVEC_MICROLIB_BUFFER_SIZE %d", f.Microlib.Geometry.BufferSize)
	w("#define HQQ_RPCVEC_MICROLIB_BUFFER_COUNT %d", f.Microlib.Geometry.BufferCount)
	w("#define HQQ_RPCVEC_CHUNKING_BUFFER_SIZE %d", f.Chunking.BufferSize)
	w("")

	w("/* Interface digests (BINDGEN.md 2.6 to 2.8) and canonical texts. */")
	cDigest(w, "microlib", f.Microlib)
	cDigest(w, "sqlite_lowlevel", f.SQLiteLowlevel)
	w("")

	cGroup(w, "microlib", f.Microlib.Frames)
	cGroup(w, "chunking", f.Chunking.Frames)
	cGroup(w, "wrap", f.Wrap.Frames)

	w("#ifdef __cplusplus")
	w("}")
	w("#endif")
	w("")
	w("#endif /* HQQ_TESTS_RPC_VECTORS_H */")
	return []byte(o.String())
}

func cDigest(w func(string, ...any), name string, s Service) {
	raw, _ := hex.DecodeString(s.Digest)
	w("static const unsigned char hqq_rpcvec_%s_digest[32] = {", name)
	cBytes(w, raw)
	w("};")
	w("static const char hqq_rpcvec_%s_canonical[] = %s;", name, cString(s.Canonical))
}

func cGroup(w func(string, ...any), group string, frames []Frame) {
	upper := strings.ToUpper(group)
	w("/* Group %q (BINDGEN.md 4.14), in document order. */", group)
	for _, fr := range frames {
		raw, _ := hex.DecodeString(fr.Hex)
		w("static const unsigned char hqq_rpcvec_data_%s[%d] = {", fr.Name, len(raw))
		cBytes(w, raw)
		w("};")
	}
	w("#define HQQ_RPCVEC_%s_COUNT %d", upper, len(frames))
	w("static const hqq_rpcvec_frame hqq_rpcvec_%s[HQQ_RPCVEC_%s_COUNT] = {", group, upper)
	for _, fr := range frames {
		raw, _ := hex.DecodeString(fr.Hex)
		dir := "HQQ_RPCVEC_C2S"
		if fr.Dir == dirS2C {
			dir = "HQQ_RPCVEC_S2C"
		}
		w("    {%s, UINT32_C(%d), %s, hqq_rpcvec_data_%s, %d},", cString(fr.Name), fr.ID, dir, fr.Name, len(raw))
	}
	w("};")
	w("")
}

// cBytes writes raw as 0xNN values, 16 per line.
func cBytes(w func(string, ...any), raw []byte) {
	for i := 0; i < len(raw); i += 16 {
		end := min(i+16, len(raw))
		parts := make([]string, 0, 16)
		for _, b := range raw[i:end] {
			parts = append(parts, fmt.Sprintf("0x%02x", b))
		}
		w("    %s,", strings.Join(parts, ", "))
	}
}

// cString renders s as a C string literal; every byte that is not a letter, digit or underscore is octal (the
// rule of c_string in c/tools/gen_constants.py, which also escapes the underscore), so that no trigraph or
// escape can change the meaning.
func cString(s string) string {
	var sb strings.Builder
	sb.WriteByte('"')
	for i := range len(s) {
		c := s[i]
		if c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' {
			sb.WriteByte(c)
			continue
		}
		fmt.Fprintf(&sb, "\\%03o", c)
	}
	sb.WriteByte('"')
	return sb.String()
}
