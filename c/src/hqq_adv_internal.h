/* ---- Constants --------------------------------------------------------------------- */

/* AdvFlag bits (1.0 section 10.4; AdvFlagMeta is 1.1 section 3). */
#define ADV_BEGIN 0x01u
#define ADV_END 0x02u
#define ADV_ABORT 0x04u
#define ADV_REQUEST 0x08u
#define ADV_RESPONSE 0x10u
#define ADV_ERROR 0x20u
#define ADV_META 0x40u
#define ADV_KNOWN_FLAGS 0x7Fu
#define ADV_KIND_MASK (ADV_REQUEST | ADV_RESPONSE)

/* Opcode of OpCancel (1.1 section 2). */
#define ADV_OP_CANCEL 0x07u

/* Protocol version of this implementation (1.1). */
#define ADV_MAJOR 1u
#define ADV_MINOR 1u
#define ADV_FEATURES_SUPPORTED HQQ_FEATURES_ALL

/* Error codes on the wire (SPEC 12). */
#define ADV_CODE_CONN_NOT_FOUND HQQ_ERRCODE_CONN_NOT_FOUND
#define ADV_CODE_INVALID_OP HQQ_ERRCODE_INVALID_OP
#define ADV_CODE_BUFFER_OVERFLOW HQQ_ERRCODE_BUFFER_OVERFLOW
#define ADV_CODE_SHUTTING_DOWN HQQ_ERRCODE_SHUTTING_DOWN

/* Limits and defaults. */
#define ADV_ABANDONED_CAP 4096u
#define ADV_REFUSED_CAP 1024u
#define ADV_REASSEMBLY_OVERHEAD 256u
#define ADV_MIN_QUEUE 1u
#define ADV_CONTROL_MIN 16u
#define ADV_MAX_WORKERS 64u
#define ADV_POLL_NS (UINT64_C(50) * 1000u * 1000u)
#define ADV_ABORT_NS (UINT64_C(100) * 1000u * 1000u)
#define ADV_TIMER_NS (UINT64_C(2) * 1000u * 1000u)
#define ADV_INLINE_NS (UINT64_C(200) * 1000u)      /* an inline handler may hold the dispatcher this long */
#define ADV_WATCH_IDLE_TICKS 4u                    /* quiet watchdog ticks before the timer slows down */
#define ADV_LISTEN_GRACE_NS (UINT64_C(2) * 1000u * 1000u * 1000u) /* default grace of held stream requests */
#define ADV_MIN_CLASS 6u  /* smallest payload class: 64 bytes */
#define ADV_MAX_CLASS 40u /* largest payload class */
#define ADV_CLASS_COUNT (ADV_MAX_CLASS + 1u)
#define ADV_POOL_KEEP 16u /* free buffers kept per class */

/* Negotiation attempt states (SPEC 10.1). */
typedef enum adv_neg_state {
    ADV_NEG_NONE = 0,
    ADV_NEG_NEGOTIATING,
    ADV_NEG_DONE,
    ADV_NEG_FAILED
} adv_neg_state;

/* ---- Pools and messages -------------------------------------------------------------- */

typedef struct adv_pool {
    hqq_spin lock;
    hqq_msg *free[ADV_CLASS_COUNT];
    unsigned nfree[ADV_CLASS_COUNT];
    unsigned refs;     /* the owner link and every outstanding message */
    int closed;        /* the owner link was closed */
    hqq_allocator alloc;
    int alloc_set;
} adv_pool;

/* A message: header followed by the payload in the same allocation. */
struct hqq_msg {
    hqq_msg *next;          /* free list / queue link */
    adv_pool *pool;         /* holds one reference while outstanding */
    uint64_t cap;           /* payload capacity (2^cls) */
    uint64_t len;           /* payload length */
    unsigned char *data;    /* payload start */
    uint64_t conn;          /* stream id */
    uint64_t msg_id;
    uint64_t aux;           /* request: method; response: status (with ADV_ERROR) */
    uint32_t flags;         /* full AdvFlags of the message */
    uint8_t cls;
    uint8_t has_budget;     /* request metadata (1.1 section 3) */
    uint8_t has_caller;
    uint8_t has_trace;
    uint64_t budget_ns;
    uint64_t t0_mono;       /* arrival of the Begin frame (monotonic) */
    uint64_t caller;
    uint8_t trace[16];
    struct hqq_req_ctx *rc; /* request context while the request is handled */
};

/* ---- Queues ---------------------------------------------------------------------------- */

typedef struct adv_queue {
    void **items;
    uint64_t cap;
    uint64_t head;
    uint64_t count;
} adv_queue;

/* ---- Streams ---------------------------------------------------------------------------- */

typedef enum adv_stream_state {
    ADV_ST_OPEN = 0,
    ADV_ST_CLOSED_LOCAL = 1, /* Close() ran here */
    ADV_ST_CLOSED_PEER = 2   /* OpConnClose arrived */
} adv_stream_state;

struct hqq_stream {
    struct hqq_adv *a;
    uint64_t id;
    int state;               /* adv_stream_state, under a->lock */
    int registered;          /* in a->reg */
    adv_queue q;             /* hqq_msg * */
    hqq_stream *next_all;    /* every stream object, freed at close */
};

/* An OpenStream waiting for the peer's answer (on the caller's stack). */
typedef struct adv_open {
    struct adv_open *next;
    uint64_t id;
    int done;
    hqq_status status;
} adv_open;

/* ---- Calls and key sets ------------------------------------------------------------ */

typedef struct adv_call {
    struct adv_call *next;
    uint64_t conn;
    uint64_t msg_id;
    int done;                /* a response or failure was delivered */
    hqq_status status;
    hqq_msg *resp;           /* the response (status HQQ_OK or HQQ_ERR_RESPONSE) */
} adv_call;

typedef struct adv_key {
    uint64_t conn;
    uint64_t msg_id;
    uint32_t kind;
} adv_key;

/* ---- Reassembly ------------------------------------------------------------------- */

typedef struct adv_asm {
    struct adv_asm *next;
    uint64_t conn;
    uint64_t msg_id;
    uint32_t kind;          /* ADV_REQUEST / ADV_RESPONSE / 0 */
    uint32_t hdr_flags;     /* flags of the Begin frame minus Begin/End */
    uint64_t aux;           /* aux of the Begin frame */
    uint64_t total;
    uint64_t next_off;
    uint64_t charge;
    uint64_t t0_mono;
    hqq_msg *msg;           /* buffer of size total */
} adv_asm;

/* Outcome of one OpConnCopy frame (adv_handle_copy). */
typedef struct adv_copy_out {
    hqq_msg *complete;       /* a finished message to route */
    int refused_request;     /* a request refused by the reassembly limit */
    int refused_response;    /* a response refused by the reassembly limit */
    uint64_t refused_conn;
    uint64_t refused_msg;
} adv_copy_out;

/* ---- Control queue ---------------------------------------------------------------- */

typedef struct adv_ctl_job {
    unsigned op;             /* packet opcode; zero-length payload */
    uint64_t ops[7];
    hqq_stream *accept;      /* OpConnAccept: stream to publish to AcceptStream */
} adv_ctl_job;

/* A stream request held while the link is not listening (SPEC 10.3). */
typedef struct adv_held {
    uint64_t id;
    uint64_t deadline;       /* monotonic ns: refused when it has passed */
} adv_held;

/* ---- Request contexts ------------------------------------------------------------- */

enum adv_req_end {
    ADV_REQ_LIVE = 0,
    ADV_REQ_CANCELED,     /* OpCancel from the requester: the handler is canceled, no response */
    ADV_REQ_DEADLINE,     /* the budget passed: no response */
    ADV_REQ_STREAM_GONE,  /* the stream was closed (either side): the response is still tried */
    ADV_REQ_SERVE_END,    /* Serve ended or the link closed: the response is still tried */
    ADV_REQ_HANDLED       /* the handler returned */
};

struct hqq_req_ctx {
    struct hqq_adv *a;
    struct hqq_req_ctx *next;     /* in-flight registry */
    struct hqq_req_ctx *pool_next;
    uint64_t conn;
    uint64_t msg_id;
    int end;                      /* enum adv_req_end, under a->lock */
    int has_deadline;
    uint64_t deadline_mono;
    hqq_msg *req;                 /* the request while in flight */
};

/* Response writer handed to a handler (ResponseWriter of the Go API). */
struct hqq_response {
    struct hqq_adv *a;
    hqq_req_ctx *ctx;
    hqq_msg *body;                /* pooled body buffer, NULL when empty */
    uint64_t body_len;
    int failed;                   /* WriteError was called */
    uint64_t status;
};

struct hqq_request {
    hqq_msg *msg;
};

/* ---- Threads ------------------------------------------------------------------------ */

typedef struct adv_worker {
    struct adv_worker *next;
    hqq_plat_thread *th;
    _Atomic int done;             /* retired dispatcher: its thread function is about to return */
} adv_worker;

/* A request the dispatcher thread runs itself, like the Go Serve on its receiving goroutine.
 * Lives on that thread's stack; the fields marked "lock" belong to a->lock. */
typedef struct adv_inline {
    hqq_msg *msg;                 /* claimed by adv_route, taken by the dispatcher loop */
    hqq_req_ctx *ctx;
    hqq_handler_fn fn;
    void *user;
    int escalated;                /* lock: the receive role moved to another thread */
    adv_worker *retired;          /* lock: the node that owns this thread once escalated */
} adv_inline;

/* Wake events. adv_wake_locked() wakes every parked thread; adv_wake_events_locked() only the
 * threads parked for one of the named events (adv_park_events_locked), so the request path does
 * not wake the call waiters, the control sender or the timer thread. */
#define ADV_EV_WORK 0x1u  /* a request was queued: idle workers */
#define ADV_EV_SPAWN 0x2u /* the queue outgrew the workers: Serve starts one */
#define ADV_EV_DONE 0x4u  /* a request finished: queue room, shutdown and Serve's drain */
#define ADV_EV_TIMER 0x8u /* an inline handler started while the timer thread sleeps long */

typedef struct adv_waiter {
    struct adv_waiter *next;
    hqq_plat_event *ev;
    unsigned events;
} adv_waiter;

/* ---- The link ---------------------------------------------------------------------- */

struct hqq_adv {
    hqq_link *base;
    hqq_allocator alloc;
    int alloc_set;
    adv_pool *pool;                 /* separately owned: messages may outlive the link */

    /* Immutable after open. */
    uint64_t max_message;
    uint64_t max_reassembly;
    uint64_t queue_size;
    hqq_overflow overflow;
    uint64_t control_cap;
    uint64_t buffer_size;

    /* Lifecycle. */
    hqq_cancel stop;                /* signalled by close: every wait and thread ends */
    _Atomic uint32_t closing;
    _Atomic uint32_t users;         /* API calls in progress */

    hqq_spin lock;                  /* protects everything below that threads share */
    adv_waiter *wq;
    adv_waiter *waiter_free;
    adv_worker *workers_free;

    /* Protocol. */
    adv_neg_state neg;
    uint16_t version;
    uint64_t features;
    uint64_t neg_ns;
    int dispatch_started;
    int rx_failed;
    hqq_status rx_err;
    int shutting;

    /* Threads and Serve. */
    hqq_plat_thread *rx_thread;
    hqq_plat_thread *ctl_thread;
    hqq_plat_thread *timer_thread;
    int serving;
    int serve_stop;
    int listening;
    hqq_handler_fn serve_fn;
    void *serve_user;
    unsigned workers_total;
    unsigned workers_busy;          /* workers running a handler */
    adv_worker *workers;
    /* Inline handler of the dispatcher thread (under lock). inline_active spans the handler and
     * its response; inl is set while the handler runs and the receive role is still this thread's. */
    int inline_active;
    adv_inline *inl;
    uint64_t inl_start;             /* monotonic ns the inline handler started */
    uint64_t inl_seq;               /* inline handlers started */
    uint64_t inline_limit_ns;       /* ADV_INLINE_NS; tests raise it to rule out a spurious escalation */
    unsigned esc_busy;              /* handlers on retired dispatcher threads, still running */
    int timer_slow;                 /* the timer thread sleeps ADV_TIMER_NS: wake it for an inline start */
    adv_worker *retired;            /* retired dispatcher threads, joined when Serve ends */

    /* Ids. */
    uint64_t next_msg_id;           /* >= 1 */
    uint64_t next_stream_n;

    /* Streams. */
    hqq_stream *stream0;
    hqq_stream **reg;               /* registered streams */
    uint64_t nreg, capreg;
    hqq_stream *all_streams;
    adv_open *opens;
    uint64_t accept_reserved;       /* incoming streams not yet returned by AcceptStream */
    adv_queue acceptq;              /* hqq_stream * */

    /* Incoming requests. */
    adv_queue reqq;                 /* hqq_msg * */
    uint64_t inflight;
    hqq_req_ctx *reqs;
    hqq_req_ctx *reqctx_free;

    /* Calls. */
    adv_call *calls;
    adv_key *abandoned;
    uint64_t abandoned_head, abandoned_count;
    adv_key *refused;               /* dispatcher only */
    uint64_t refused_head, refused_count;
    int refused_evicted;

    /* Reassembly (dispatcher only). */
    adv_asm *asms;
    adv_asm *asm_free;
    uint64_t assembly_bytes;

    /* Control sender. */
    adv_ctl_job *ctl;
    uint64_t ctl_head, ctl_count;
    /* Stream requests held while not listening: a FIFO ring of queue_size entries. */
    adv_held *held;
    uint64_t held_head, held_count;
    uint64_t listen_grace_ns; /* 0: refuse at once */

    /* Statistics. */
    uint64_t st_messages, st_message_bytes, st_requests, st_responses;
    uint64_t st_dropped, st_abandoned, st_canceled, st_refused;
    /* Serve internals (not in hqq_adv_stats): handlers run inline, handed to a worker, and
     * inline handlers that outlived ADV_INLINE_NS. */
    uint64_t sv_inline, sv_pooled, sv_escalated;
};

