/*
 * hqq_adv_internal.h - internals of the Advanced layer (not installed).
 *
 * One short spin lock (adv->lock) protects every field of hqq_adv that the
 * threads share. Blocking waits park on adv->wq (a list of waiters, each on a
 * manual-reset event from a per-link pool). Every wait is bounded
 * (ADV_POLL_NS) and re-checks its condition, so a missed wake only costs
 * latency. adv->lock is never held across a Standard-link call that can block.
 *
 * Threads of one link: the dispatcher (receive path, the only consumer of the
 * rx ring after negotiation), the control sender (replies generated by the
 * receive path), and, while Serve runs, the request workers and a timer thread
 * (request deadlines and the escalation watchdog). Only the dispatcher touches
 * the reassembly lists. While Serve runs and nothing else does, the dispatcher
 * runs a request's handler itself (hqq_adv_route claims it, adv_run_inline runs
 * it); when it holds the receive path past adv->inline_limit_ns the timer
 * thread starts a new dispatcher thread and the old one ends after the handler
 * (escalate_locked). The dispatcher role therefore moves between threads:
 * adv->rx_thread always names the current one, the retired ones wait in
 * adv->retired until Serve joins them.
 */
