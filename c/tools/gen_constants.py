#!/usr/bin/env python3
"""Generates c/tests/generated/spec_constants.h from spec/constants.json.

The header carries every numeric constant of the protocol (offsets, sizes,
magics, opcodes, error codes, timings, platform limits) plus the packet and
layout golden vectors. The C tests compare the library against it, so a
change to spec/constants.json that the library does not follow fails the build.

Usage:
    gen_constants.py            regenerate the header
    gen_constants.py --check    exit 1 if the committed header is stale

Python 3 standard library only.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SPEC = os.path.join(REPO, "spec", "constants.json")
OUT = os.path.join(REPO, "c", "tests", "generated", "spec_constants.h")

# Sections whose integer leaves become HQQ_SPEC_<PREFIX>_<KEY> macros.
SCALAR_SECTIONS = [
    ("versions", "VERSION"),
    ("geometry", "GEOM"),
    ("ring", "RING"),
    ("ring.slot", "RING_SLOT"),
    ("packet", "PACKET"),
    ("opcodes", ""),
    ("error_codes", "ERRCODE"),
    ("advanced", "ADV"),
    ("advanced.features", "FEATURE"),
    ("advanced.frame_flags", "FRAME_FLAG"),
    ("advanced.protocol_states", "PROTO_STATE"),
    ("timing_ns", "TIMING_NS"),
    ("wait", "WAIT"),
    ("platform.linux", "LINUX"),
    ("platform.darwin", "DARWIN"),
    ("platform.freebsd", "FREEBSD"),
    ("platform.windows", "WIN"),
    ("segment", "SEG"),
    ("segment.states", "STATE"),
    ("segment.tokens", "TOKEN"),
    ("segment.endpoints", "EP_TABLE"),
    ("informative_untested", "UNTESTED"),
]


def snake(name):
    """camelCase / PascalCase / dotted-free identifiers to UPPER_SNAKE."""
    s = re.sub(r"[^A-Za-z0-9]+", "_", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.strip("_").upper()


def c_string(s):
    """A C string literal that is safe for any byte: non-alnum bytes are octal."""
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch.isascii() and ch.isalnum():
            out.append(ch)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def int_value(v):
    if isinstance(v, bool):
        return None
    if isinstance(v, int):
        return v
    if isinstance(v, str) and v.startswith("0x"):
        return int(v, 16)
    return None


def get_path(doc, dotted):
    node = doc
    for part in dotted.split("."):
        node = node[part]
    return node


def scalar_macros(prefix, node, out, seen):
    for key, value in node.items():
        v = int_value(value)
        if v is None:
            if isinstance(value, dict):
                continue  # nested tables are emitted by their own section
            continue
        name = "HQQ_SPEC_%s%s" % (prefix + "_" if prefix else "", snake(key))
        if name in seen:
            raise SystemExit("duplicate macro " + name)
        seen.add(name)
        if isinstance(value, str):
            out.append("#define %s UINT64_C(%s)" % (name, hex(v)))
        elif v < 0:
            out.append("#define %s INT64_C(%d)" % (name, v))
        else:
            out.append("#define %s UINT64_C(%d)" % (name, v))


def generate(doc):
    out = []
    seen = set()

    out.append("/* Generated by c/tools/gen_constants.py from spec/constants.json. Do not edit. */")
    out.append("#ifndef HQQ_TESTS_SPEC_CONSTANTS_H")
    out.append("#define HQQ_TESTS_SPEC_CONSTANTS_H")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#ifdef __cplusplus")
    out.append('extern "C" {')
    out.append("#endif")
    out.append("")

    # Segment layout: superblock fields and endpoint record fields.
    seg = doc["segment"]
    out.append("/* Superblock (SPEC 3.1) and endpoint record (SPEC 3.2). */")
    out.append("#define HQQ_SPEC_SB_SIZE %d" % seg["superblock_size"])
    out.append("#define HQQ_SPEC_EP_SIZE %d" % seg["endpoint_record_size"])
    out.append("#define HQQ_SPEC_MAGIC_SB UINT64_C(%s)" % seg["magic"])
    out.append("#define HQQ_SPEC_MAGIC_SB_ASCII %s" % c_string(seg["magic_ascii"]))
    out.append("#define HQQ_SPEC_KNOWN_REQUIRED_FEATURES UINT64_C(%d)" % seg["known_required_features"])
    out.append("#define HQQ_SPEC_MIN_PAGE_SIZE %d" % seg["min_page_size"])
    for f in seg["superblock_fields"]:
        base = "HQQ_SPEC_SB_%s" % snake(f["name"])
        out.append("#define %s_OFFSET %d" % (base, f["offset"]))
        out.append("#define %s_SIZE %d" % (base, f["size"]))
    for f in seg["endpoint_record_fields"]:
        base = "HQQ_SPEC_EP_%s" % snake(f["name"])
        out.append("#define %s_OFFSET %d" % (base, f["offset"]))
        out.append("#define %s_SIZE %d" % (base, f["size"]))
    out.append("")

    # Ring header and slot (SPEC 7.1).
    ring = doc["ring"]
    out.append("/* Ring header and slot (SPEC 7.1). */")
    out.append("#define HQQ_SPEC_MAGIC_RING UINT64_C(%s)" % ring["magic"])
    for f in ring["header_fields"]:
        base = "HQQ_SPEC_RING_%s" % snake(f["name"])
        out.append("#define %s_OFFSET %d" % (base, f["offset"]))
        out.append("#define %s_SIZE %d" % (base, f["size"]))
    out.append("")

    # Layout vectors (SPEC 2.1).
    vectors = seg["layout_vectors"]
    out.append("typedef struct hqq_spec_layout_vector {")
    out.append("    uint64_t page_size, buffer_count, buffer_size;")
    out.append("    uint64_t ring0, buffers0, ring1, buffers1, total;")
    out.append("} hqq_spec_layout_vector;")
    out.append("#define HQQ_SPEC_LAYOUT_VECTOR_COUNT %d" % len(vectors))
    out.append("static const hqq_spec_layout_vector hqq_spec_layout_vectors[HQQ_SPEC_LAYOUT_VECTOR_COUNT] = {")
    for v in vectors:
        out.append("    {UINT64_C(%d), UINT64_C(%d), UINT64_C(%d), UINT64_C(%d), UINT64_C(%d), UINT64_C(%d), UINT64_C(%d), UINT64_C(%d)}," % (
            v["page_size"], v["buffer_count"], v["buffer_size"], v["ring0"], v["buffers0"],
            v["ring1"], v["buffers1"], v["total"]))
    out.append("};")
    out.append("")

    # Packet vectors (SPEC 9.1, 9.2): opcode, operands, 64 bytes.
    pv = doc["packet_vectors"]
    out.append("typedef struct hqq_spec_packet_vector {")
    out.append("    const char *name;")
    out.append("    unsigned opcode;")
    out.append("    unsigned operand_count;")
    out.append("    uint64_t operands[7];")
    out.append("    unsigned char bytes[64];")
    out.append("} hqq_spec_packet_vector;")
    out.append("#define HQQ_SPEC_PACKET_VECTOR_COUNT %d" % len(pv))
    out.append("static const hqq_spec_packet_vector hqq_spec_packet_vectors[HQQ_SPEC_PACKET_VECTOR_COUNT] = {")
    for name, v in pv.items():
        hexs = v["hex"]
        if len(hexs) != 128:
            raise SystemExit("packet vector %s is not 64 bytes" % name)
        ops = list(v["operands"]) + [0] * (7 - len(v["operands"]))
        byte_list = ", ".join("0x%s" % hexs[i:i + 2] for i in range(0, 128, 2))
        out.append("    {%s, %d, %d, {%s}, {%s}}," % (
            c_string(name), v["opcode"], len(v["operands"]),
            ", ".join("UINT64_C(%d)" % o for o in ops), byte_list))
    out.append("};")
    out.append("")

    # Name vectors (SPEC 11.1) and the Windows object-name vectors.
    nv = doc["platform"]["name_validation"]
    invalid = nv["invalid_vectors"]
    out.append("typedef struct hqq_spec_bytes { const char *s; size_t len; } hqq_spec_bytes;")
    out.append("#define HQQ_SPEC_INVALID_NAME_COUNT %d" % len(invalid))
    out.append("static const hqq_spec_bytes hqq_spec_invalid_names[HQQ_SPEC_INVALID_NAME_COUNT] = {")
    for s in invalid:
        out.append("    {%s, %d}," % (c_string(s), len(s.encode("utf-8"))))
    out.append("};")
    wv = doc["platform"]["windows"]["name_vectors"]
    out.append("typedef struct hqq_spec_name_vector { const char *name; const char *object; } hqq_spec_name_vector;")
    out.append("#define HQQ_SPEC_WIN_NAME_VECTOR_COUNT %d" % len(wv))
    out.append("static const hqq_spec_name_vector hqq_spec_win_name_vectors[HQQ_SPEC_WIN_NAME_VECTOR_COUNT] = {")
    for v in wv:
        out.append("    {%s, %s}," % (c_string(v["name"]), c_string(v["object"])))
    out.append("};")
    win_invalid = doc["platform"]["windows"]["invalid_name_vectors"]
    out.append("#define HQQ_SPEC_WIN_INVALID_NAME_COUNT %d" % len(win_invalid))
    out.append("static const hqq_spec_bytes hqq_spec_win_invalid_names[HQQ_SPEC_WIN_INVALID_NAME_COUNT] = {")
    for s in win_invalid:
        out.append("    {%s, %d}," % (c_string(s), len(s.encode("utf-8"))))
    out.append("};")
    out.append("")

    # Scalar macros.
    out.append("/* Scalar constants (every integer leaf of the listed sections). */")
    for section, prefix in SCALAR_SECTIONS:
        scalar_macros(prefix, get_path(doc, section), out, seen)
    out.append("")

    # Opcodes and error codes by name, for direct comparison with the library.
    out.append("/* Name mapping of the opcode and error-code tables. */")
    out.append("#define HQQ_SPEC_OPCODE_ERROR_NAME \"OpError\"")
    out.append("")

    out.append("#ifdef __cplusplus")
    out.append("}")
    out.append("#endif")
    out.append("")
    out.append("#endif /* HQQ_TESTS_SPEC_CONSTANTS_H */")
    out.append("")
    return "\n".join(out)


def load():
    with open(SPEC, "r", encoding="utf-8") as fh:
        return json.load(fh)


def main(argv):
    text = generate(load())
    if "--check" in argv:
        try:
            with open(OUT, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            sys.stderr.write("stale: %s; run python3 c/tools/gen_constants.py\n" % os.path.relpath(OUT, REPO))
            return 1
        print("up to date: %s" % os.path.relpath(OUT, REPO))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s" % os.path.relpath(OUT, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
