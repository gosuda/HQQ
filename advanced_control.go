package hqq

import (
	"context"

	"gosuda.org/hqq/internal/protocol"
)

// minControlQueue is the smallest capacity of the control queue.
const minControlQueue = 16

// controlKind tells the control sender what a queued packet is for.
type controlKind uint8

const (
	// controlReply: send the packet.
	controlReply controlKind = iota
	// controlRefusedRequest: send the error response of a request refused
	// by MaxReassemblyBytes; counts as a response.
	controlRefusedRequest
	// controlAccept: send the OpConnAccept of an incoming stream and, once
	// it is enqueued on the tx ring, make the stream visible to
	// AcceptStream. The stream holds an acceptSlots slot.
	controlAccept
)

// controlJob is one reply generated by the receive path.
type controlJob struct {
	packet protocol.Packet
	kind   controlKind
}

// The receive path (the dispatcher, or a goroutine receiving synchronously
// while it holds receiveMu) must never wait for the tx ring: if two peers
// flood each other, both tx rings fill up and each receiver would wait for a
// peer that no longer drains. The replies the receive path generates
// (OpConnAccept, refusals of OpConnCreate, error responses to requests
// refused by MaxReassemblyBytes) are therefore queued on a bounded queue
// served by a dedicated control-sender goroutine, which is the only
// goroutine that waits for the tx ring on behalf of the receive path. The
// goroutine starts on the first reply and stops in Close.
//
// A full queue never blocks the receiver: the reply is dropped. A dropped
// reply to an OpConnCreate (accept or refusal) is counted in
// AdvancedStats.DroppedMessages and leaves the peer's OpenStream waiting
// until its own context ends; a dropped error response to a refused request
// (already counted when the request was refused) leaves the peer's Call
// waiting likewise. The queue holds max(BufferCount, 16) replies.

// controlQueue returns the control queue, starting the control sender if
// needed. It returns nil once the link is closing.
func (l *AdvancedLink) controlQueue() chan controlJob {
	if l.ctrlStarted.Load() {
		return l.ctrlQueue
	}
	l.dispatchMu.Lock()
	defer l.dispatchMu.Unlock()
	if l.closing {
		return nil
	}
	if !l.ctrlStarted.Load() {
		ctx, cancel := context.WithCancel(context.Background())
		l.ctrlQueue = make(chan controlJob, max(l.slink.bufferCount, minControlQueue))
		l.ctrlCancel = cancel
		l.ctrlStarted.Store(true)
		go l.controlLoop(ctx, l.ctrlQueue)
	}
	return l.ctrlQueue
}

// enqueueControl queues job without blocking and reports whether it was
// queued.
func (l *AdvancedLink) enqueueControl(job controlJob) bool {
	if queue := l.controlQueue(); queue != nil {
		select {
		case queue <- job:
			return true
		default:
		}
	}
	return false
}

func (l *AdvancedLink) controlLoop(ctx context.Context, queue <-chan controlJob) {
	defer close(l.ctrlDone)
	for {
		select {
		case <-ctx.Done():
			return
		case job := <-queue:
			l.runControlJob(ctx, job)
		}
	}
}

func (l *AdvancedLink) runControlJob(ctx context.Context, job controlJob) {
	err := l.sendPacket(ctx, job.packet)
	switch job.kind {
	case controlRefusedRequest:
		if err == nil {
			l.stats.responses.Add(1)
		}
	case controlAccept:
		connID := job.packet.Operand(0)
		if err != nil {
			l.forgetConnection(connID)
			l.releaseAcceptSlot()
			return
		}
		// The slot reserved when the create was received guarantees room.
		l.acceptCh <- connID
	}
}

func (l *AdvancedLink) releaseAcceptSlot() {
	select {
	case <-l.acceptSlots:
	default:
	}
}

func (l *AdvancedLink) forgetConnection(connID uint64) {
	l.controlMu.Lock()
	delete(l.connections, connID)
	l.controlMu.Unlock()
}

// refuseStream queues the refusal of an OpConnCreate.
func (l *AdvancedLink) refuseStream(connID uint64, code ErrorCode) {
	job := controlJob{packet: protocol.NewPacket(protocol.OpError, connID, uint64(code)), kind: controlReply}
	if !l.enqueueControl(job) {
		l.stats.droppedMessages.Add(1)
	}
}

// refuseRequest queues the error response (ErrCodeBufferOverflow) of a
// request refused by MaxReassemblyBytes. It is best effort: the response is
// not sent if FeatureRequestResponse is not negotiated or the queue is full.
func (l *AdvancedLink) refuseRequest(request AdvancedMessage) {
	if l.requireFeature(FeatureRequestResponse) != nil {
		return
	}
	const flags = AdvFlagBegin | AdvFlagEnd | AdvFlagResponse | AdvFlagError
	l.enqueueControl(controlJob{
		packet: protocol.NewConnCopyPacket(request.ConnectionID, request.MessageID, 0, 0, 0, flags, uint64(ErrCodeBufferOverflow)),
		kind:   controlRefusedRequest,
	})
}
